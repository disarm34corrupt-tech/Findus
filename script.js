/* =====================================================
   GAME
===================================================== */

let foundCount = 0;

let activePerson = null;


/* =====================================================
   INITIALIZE
===================================================== */

document.addEventListener(
    "DOMContentLoaded",
    function () {

        const intro =
            document.getElementById("intro");

        const room =
            document.getElementById("room");

        const gameArea =
            document.getElementById("gameArea");

        const counter =
            document.getElementById("foundCount");

        const popup =
            document.getElementById("foundPopup");

        const decoyPopup =
            document.getElementById("decoyPopup");

        const completePopup =
            document.getElementById("completePopup");

        const foundTitle =
            document.getElementById("foundTitle");

        const foundMessage =
            document.getElementById("foundMessage");

        const decoyMessage =
            document.getElementById("decoyMessage");

        const enterButton =
            document.getElementById("enterButton");

        const closeFound =
            document.getElementById("closeFound");

        const closeDecoy =
            document.getElementById("closeDecoy");


        /* =================================================
           ENTER ROOM
        ================================================= */

        enterButton.addEventListener(
            "click",
            function () {

                intro.classList.add(
                    "hidden"
                );

                room.classList.remove(
                    "hidden"
                );

            }
        );


        /* =================================================
           CREATE CHARACTER
        ================================================= */

        function createCharacter(
            person,
            isSpecial
        ) {

            const image =
                document.createElement("img");


            image.src =
                person.image;

            image.alt =
                person.name ||
                "person";


            image.classList.add(
                "person"
            );


            image.classList.add(
                isSpecial
                    ? "special"
                    : "decoy"
            );


            const position =
                layout[person.id];


            if (position) {

                image.style.left =
                    position.left;

                image.style.bottom =
                    position.bottom;

                image.style.width =
                    position.width;

                image.style.zIndex =
                    position.z;

            }


            /* ---------------------------------------------
               CLICK / TOUCH
            --------------------------------------------- */

            image.addEventListener(
                "click",
                function (event) {

                    event.preventDefault();

                    event.stopPropagation();


                    if (isSpecial) {

                        findSpecial(
                            person,
                            image
                        );

                    } else {

                        clickDecoy(
                            person
                        );

                    }

                }
            );


            gameArea.appendChild(
                image
            );

        }


        /* =================================================
           FIND SPECIAL
        ================================================= */

        function findSpecial(
            person,
            element
        ) {

            if (
                element.classList.contains(
                    "found"
                )
            ) {

                return;

            }


            activePerson = {

                person: person,

                element: element

            };


            foundTitle.textContent =
                person.name;

            foundMessage.textContent =
                person.message;


            popup.classList.remove(
                "hidden"
            );

        }


        /* =================================================
           CLOSE FOUND POPUP
        ================================================= */

        function closeFoundPopup() {

            popup.classList.add(
                "hidden"
            );


            if (!activePerson) {

                return;

            }


            const element =
                activePerson.element;


            if (
                !element.classList.contains(
                    "found"
                )
            ) {

                element.classList.add(
                    "found"
                );


                foundCount++;


                counter.textContent =
                    foundCount;

            }


            activePerson = null;


            if (
                foundCount ===
                specialPeople.length
            ) {

                setTimeout(
                    function () {

                        completePopup.classList.remove(
                            "hidden"
                        );

                    },
                    400
                );

            }

        }


        /* =================================================
           DECOY
        ================================================= */

        function clickDecoy(
            person
        ) {

            decoyMessage.textContent =
                person.message;


            decoyPopup.classList.remove(
                "hidden"
            );

        }


        /* =================================================
           CLOSE DECOY
        ================================================= */

        function closeDecoyPopup() {

            decoyPopup.classList.add(
                "hidden"
            );

        }


        /* =================================================
           CLOSE BUTTONS
        ================================================= */

        closeFound.addEventListener(
            "click",
            closeFoundPopup
        );


        closeDecoy.addEventListener(
            "click",
            closeDecoyPopup
        );


        /* =================================================
           CLICK OUTSIDE POPUPS
        ================================================= */

        popup.addEventListener(
            "click",
            function (event) {

                if (
                    event.target === popup
                ) {

                    closeFoundPopup();

                }

            }
        );


        decoyPopup.addEventListener(
            "click",
            function (event) {

                if (
                    event.target === decoyPopup
                ) {

                    closeDecoyPopup();

                }

            }
        );


        /* =================================================
           BUILD GAME
        ================================================= */

        specialPeople.forEach(
            function (person) {

                createCharacter(
                    person,
                    true
                );

            }
        );


        decoyPeople.forEach(
            function (person) {

                createCharacter(
                    person,
                    false
                );

            }
        );


    }
);
