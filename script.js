/* =====================================================
   GAME VARIABLES
===================================================== */

let foundCount = 0;

let activePerson = null;


/* =====================================================
   ELEMENTS
===================================================== */

const intro =
    document.getElementById("intro");

const room =
    document.getElementById("room");

const gameArea =
    document.getElementById("gameArea");

const counter =
    document.getElementById("foundCount");

const popup =
    document.getElementById("foundPopup");

const decoyPopup =
    document.getElementById("decoyPopup");

const completePopup =
    document.getElementById("completePopup");

const foundTitle =
    document.getElementById("foundTitle");

const foundMessage =
    document.getElementById("foundMessage");

const decoyMessage =
    document.getElementById("decoyMessage");

const enterButton =
    document.getElementById("enterButton");

const closeFound =
    document.getElementById("closeFound");

const closeDecoy =
    document.getElementById("closeDecoy");


/* =====================================================
   ENTER ROOM
===================================================== */

function enterRoom() {

    intro.classList.add("hidden");

    room.classList.remove("hidden");

}


/* =====================================================
   CREATE CHARACTER
===================================================== */

function createCharacter(person, isSpecial) {

    const image =
        document.createElement("img");


    /* IMAGE */

    image.src = person.image;

    image.alt =
        person.name || "person";


    /* CLASS */

    image.classList.add("person");

    image.classList.add(
        isSpecial ? "special" : "decoy"
    );


    /* POSITION */

    const position =
        layout[person.id];


    if (position) {

        image.style.left =
            position.left;

        image.style.bottom =
            position.bottom;

        image.style.width =
            position.width;

        image.style.zIndex =
            position.z;

    }


    /* CLICK */

    image.addEventListener(
        "click",
        function () {

            if (isSpecial) {

                findSpecial(
                    person,
                    image
                );

            } else {

                clickDecoy(
                    person
                );

            }

        }
    );


    /* ADD TO GAME */

    gameArea.appendChild(image);

}


/* =====================================================
   FIND SPECIAL
===================================================== */

function findSpecial(
    person,
    element
) {

    if (
        element.classList.contains("found")
    ) {

        return;

    }


    activePerson = {

        person: person,

        element: element

    };


    foundTitle.textContent =
        person.name;

    foundMessage.textContent =
        person.message;


    popup.classList.remove(
        "hidden"
    );

}


/* =====================================================
   CLOSE SPECIAL POPUP
===================================================== */

function closeFoundPopup() {

    popup.classList.add(
        "hidden"
    );


    if (!activePerson) {

        return;

    }


    const element =
        activePerson.element;


    if (
        !element.classList.contains("found")
    ) {

        element.classList.add(
            "found"
        );

        foundCount++;

        counter.textContent =
            foundCount;

    }


    activePerson = null;


    /* ALL SPECIAL PEOPLE FOUND */

    if (
        foundCount ===
        specialPeople.length
    ) {

        setTimeout(
            function () {

                completePopup.classList.remove(
                    "hidden"
                );

            },
            500
        );

    }

}


/* =====================================================
   DECOY CLICK
===================================================== */

function clickDecoy(person) {

    decoyMessage.textContent =
        person.message;

    decoyPopup.classList.remove(
        "hidden"
    );

}


/* =====================================================
   CLOSE DECOY POPUP
===================================================== */

function closeDecoyPopup() {

    decoyPopup.classList.add(
        "hidden"
    );

}


/* =====================================================
   EVENTS
===================================================== */

enterButton.addEventListener(
    "click",
    enterRoom
);

closeFound.addEventListener(
    "click",
    closeFoundPopup
);

closeDecoy.addEventListener(
    "click",
    closeDecoyPopup
);


/* =====================================================
   CLICK OUTSIDE SPECIAL POPUP
===================================================== */

popup.addEventListener(
    "click",
    function (event) {

        if (
            event.target === popup
        ) {

            closeFoundPopup();

        }

    }
);


/* =====================================================
   CLICK OUTSIDE DECOY POPUP
===================================================== */

decoyPopup.addEventListener(
    "click",
    function (event) {

        if (
            event.target === decoyPopup
        ) {

            closeDecoyPopup();

        }

    }
);


/* =====================================================
   BUILD GAME
===================================================== */

function buildGame() {


    /* CREATE SPECIAL PEOPLE */

    specialPeople.forEach(
        function (person) {

            createCharacter(
                person,
                true
            );

        }
    );


    /* CREATE DECOYS */

    decoyPeople.forEach(
        function (person) {

            createCharacter(
                person,
                false
            );

        }
    );

}


/* =====================================================
   START
===================================================== */

buildGame();
