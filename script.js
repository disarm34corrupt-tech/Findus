/* =====================================================
   GAME VARIABLES
===================================================== */

let foundCount = 0;

let activePerson = null;


/* =====================================================
   ELEMENTS
===================================================== */

const intro =
    document.getElementById("intro");

const room =
    document.getElementById("room");

const gameArea =
    document.getElementById("gameArea");

const counter =
    document.getElementById("foundCount");

const popup =
    document.getElementById("foundPopup");

const decoyPopup =
    document.getElementById("decoyPopup");

const completePopup =
    document.getElementById("completePopup");

const foundTitle =
    document.getElementById("foundTitle");

const foundMessage =
    document.getElementById("foundMessage");

const enterButton =
    document.getElementById("enterButton");

const closeFound =
    document.getElementById("closeFound");

const closeDecoy =
    document.getElementById("closeDecoy");


/* =====================================================
   ENTER ROOM
===================================================== */

enterButton.addEventListener(
    "click",
    enterRoom
);


function enterRoom() {

    intro.classList.add("hidden");

    room.classList.remove("hidden");

}


/* =====================================================
   CREATE CHARACTER
===================================================== */

function createCharacter(
    person,
    isSpecial
) {

    const image =
        document.createElement("img");


    image.src =
        person.image;


    image.alt =
        person.name || "Person";


    image.classList.add(
        "person"
    );


    if (isSpecial) {

        image.classList.add(
            "special"
        );

    }


    const position =
        layout[person.id];


    if (position) {

        image.style.left =
            position.left;

        image.style.bottom =
            position.bottom;

        image.style.width =
            position.width;

        image.style.zIndex =
            position.z;

    }


    image.addEventListener(
        "click",
        function () {

            if (isSpecial) {

                findSpecial(
                    person,
                    image
                );

            }

            else {

                clickDecoy(
                    person
                );

            }

        }
    );


    gameArea.appendChild(
        image
    );

}


/* =====================================================
   SPECIAL PERSON
===================================================== */

function findSpecial(
    person,
    element
) {

    if (
        element.classList.contains(
            "found"
        )
    ) {

        return;

    }


    activePerson = {

        person:
            person,

        element:
            element

    };


    foundTitle.textContent =
        person.name;


    foundMessage.textContent =
        person.message;


    popup.classList.remove(
        "hidden"
    );

}


/* =====================================================
   CLOSE SPECIAL
===================================================== */

function closeFoundPopup() {

    popup.classList.add(
        "hidden"
    );


    if (!activePerson) {

        return;

    }


    const element =
        activePerson.element;


    if (
        !element.classList.contains(
            "found"
        )
    ) {

        element.classList.add(
            "found"
        );


        foundCount++;


        counter.textContent =
            foundCount;

    }


    activePerson = null;


    if (
        foundCount ===
        specialPeople.length
    ) {

        setTimeout(
            function () {

                completePopup.classList.remove(
                    "hidden"
                );

            },
            500
        );

    }

}


/* =====================================================
   DECOY
===================================================== */

function clickDecoy(person) {

    document.querySelector(
        "#decoyPopup .popup-box p:last-child"
    ).textContent =
        person.message;


    decoyPopup.classList.remove(
        "hidden"
    );

}


/* =====================================================
   CLOSE DECOY
===================================================== */

function closeDecoyPopup() {

    decoyPopup.classList.add(
        "hidden"
    );

}


/* =====================================================
   BUTTON EVENTS
===================================================== */

closeFound.addEventListener(
    "click",
    closeFoundPopup
);


closeDecoy.addEventListener(
    "click",
    closeDecoyPopup
);


/* =====================================================
   CLICK OUTSIDE POPUP
===================================================== */

popup.addEventListener(
    "click",
    function (event) {

        if (
            event.target === popup
        ) {

            closeFoundPopup();

        }

    }
);


decoyPopup.addEventListener(
    "click",
    function (event) {

        if (
            event.target === decoyPopup
        ) {

            closeDecoyPopup();

        }

    }
);


/* =====================================================
   BUILD GAME
===================================================== */

function buildGame() {


    /*
       SPECIAL PEOPLE
    */

    specialPeople.forEach(
        function (person) {

            createCharacter(
                person,
                true
            );

        }
    );


    /*
       DECOYS
    */

    decoyPeople.forEach(
        function (person) {

            createCharacter(
                person,
                false
            );

        }
    );

}


/* =====================================================
   START GAME
===================================================== */

buildGame();
